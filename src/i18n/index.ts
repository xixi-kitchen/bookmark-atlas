export function t(key: MessageKey, substitutions: string | string[] = []) {
  const values = Array.isArray(substitutions) ? substitutions : [substitutions];
  const native = globalThis.chrome?.i18n?.getMessage?.(key, values);
  const fallback = isChineseUi() ? ZH_MESSAGES[key] ?? FALLBACK_MESSAGES[key] : FALLBACK_MESSAGES[key];
  return native || formatFallback(fallback, values);
}

export function getExcalidrawLanguage() {
  return isChineseUi() ? 'zh-CN' : 'en';
}

export function getUiLanguage() {
  return isChineseUi() ? 'zh-CN' : 'en';
}

function formatFallback(template: string, values: string[]) {
  return values.reduce((message, value, index) => message.replaceAll(`$${index + 1}`, value), template);
}

function isChineseUi() {
  const screenshotParams = isStoreScreenshotMode() && typeof location !== 'undefined'
    ? new URLSearchParams(location.search)
    : null;
  const screenshotLocale = screenshotParams?.get('lang') ?? null;
  if (screenshotLocale === 'zh-CN' || screenshotLocale === 'zh_CN') return true;
  if (screenshotLocale === 'en') return false;
  const locale = globalThis.chrome?.i18n?.getUILanguage?.() ?? globalThis.navigator?.language ?? 'en';
  return locale.toLowerCase().startsWith('zh');
}
